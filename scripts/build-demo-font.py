#!/usr/bin/env python3
"""Regenerate scripts/demo_font.py, the glyph atlas used by demo_documents.py. Development tool only.

The nightly demo reset runs in a bare python image without Pillow or fonts: demo_documents.py draws the PNG
screens from this atlas and writes the PDF with the standard Helvetica fonts, sized with the widths below.

  python3 scripts/build-demo-font.py <Inter-Regular.ttf> <Inter-SemiBold.ttf> <Helvetica.ttc>

Inter is distributed under the SIL Open Font License 1.1. Only rasterised glyphs are stored, never the font file.
Helvetica is only measured: the PDF uses the viewer's standard font, nothing of it is embedded.
"""
import base64
import struct
import sys
import zlib
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

CHARS = (''.join(chr(c) for c in range(32, 127)) +
         'àâäçéèêëîïôöùûüÿœæÀÂÄÇÉÈÊËÎÏÔÖÙÛÜŒÆ€°«»’‘“”–…·×±≤≥²³µ§•')
# name: (font file argument index, pixel size)
ATLAS = {'small': (0, 12), 'body': (0, 14), 'bold': (1, 14), 'title': (1, 19)}


def atlas(path, size):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    packed = bytearray()
    for char in CHARS:
        advance = round(font.getlength(char) * 16)
        canvas = Image.new('L', (size * 4, size * 3), 0)
        ImageDraw.Draw(canvas).text((size, size * 2), char, font=font, fill=255, anchor='ls')
        box = canvas.getbbox()
        if box is None:
            x0 = y0 = w = h = 0
            pixels = b''
        else:
            x0, y0, w, h = box[0] - size, box[1] - size * 2, box[2] - box[0], box[3] - box[1]
            # Four bits of coverage are enough for antialiased text and halve the atlas.
            pixels = bytes(v >> 4 for v in canvas.crop(box).tobytes())
        packed += struct.pack('<HHbbBB', ord(char), advance, x0, y0, w, h) + pixels
    return {'ascent': ascent, 'descent': descent, 'data': base64.b64encode(zlib.compress(bytes(packed), 9)).decode()}


def helvetica_widths(path, index):
    # Widths in 1/1000 em for the WinAnsi code points, as the PDF /Widths array expects.
    font = ImageFont.truetype(path, 1000, index=index)
    widths = []
    for code in range(32, 256):
        try:
            char = bytes([code]).decode('cp1252')
        except UnicodeDecodeError:
            char = ' '
        widths.append(round(font.getlength(char)))
    return widths


def main():
    regular, semibold, helvetica = sys.argv[1:4]
    fonts = {name: atlas((regular, semibold)[source], size) for name, (source, size) in ATLAS.items()}
    lines = ['"""Generated by scripts/build-demo-font.py. Do not edit.',
             '',
             'Glyphs rasterised from Inter (SIL Open Font License 1.1, rsms.me/inter). Helvetica widths measured for',
             'the PDF standard fonts, in 1/1000 em, for WinAnsi code points 32 to 255.',
             '"""',
             'CHARS = ' + repr(CHARS),
             'HELVETICA = ' + repr(helvetica_widths(helvetica, 0)),
             'HELVETICA_BOLD = ' + repr(helvetica_widths(helvetica, 1)),
             'FONTS = {']
    for name, value in fonts.items():
        lines.append(f"    {name!r}: {{'ascent': {value['ascent']}, 'descent': {value['descent']},")
        data = value['data']
        chunks = [data[i:i + 100] for i in range(0, len(data), 100)]
        lines.append("             'data': (" + '\n                      '.join(repr(c) for c in chunks) + ')},')
    lines.append('}')
    target = Path(__file__).with_name('demo_font.py')
    target.write_text('\n'.join(lines) + '\n')
    print(f'{target} : {target.stat().st_size} octets')


if __name__ == '__main__':
    main()
