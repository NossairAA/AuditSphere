#!/usr/bin/env python3
"""Seed the 40 synthetic audit missions of demo_dataset.py through the API. Dry run unless --apply.

Each mission follows the lifecycle of its index: program, results, evidence files generated by
demo_documents.py, findings with their review decisions, then submission, decision, withdrawal or closure.
State is reconciled from the API on every run. A private manifest anchors relative dates and records IDs for
review, but is never the only source of truth after an interrupted POST.
"""
