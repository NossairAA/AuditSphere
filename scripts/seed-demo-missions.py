# Cloudflare's browser integrity check refuses the default Python-urllib agent on the public names
# (phase 10, lot B, error 1010). Every opener, including the one behind urlopen, sends a named agent.
_opener_init = urllib.request.OpenerDirector.__init__


def _named_opener(self):
    _opener_init(self)
    self.addheaders = [('User-agent', 'AuditSphere-checks')]


urllib.request.OpenerDirector.__init__ = _named_opener

ROOT = Path(__file__).resolve().parents[1]
# Les valeurs par défaut visent la pile locale. Le cluster k3s les remplace par des variables d'environnement.
MANIFEST = Path(os.environ.get('SEED_MANIFEST', ROOT / '.local' / 'demo-missions-manifest.json'))
BASE = os.environ.get('SEED_API_BASE', 'http://localhost:8080')
TOKEN_URL = os.environ.get('SEED_TOKEN_URL', 'http://localhost:8180/realms/auditsphere/protocol/openid-connect/token')
ACCOUNTS = Path(os.environ.get('SEED_ACCOUNTS_FILE', ROOT / '.env'))
IDENT = 'auditsphere-demo-v2'
COMPANY = 'Groupe Alvéane'
NAMES = {'auditor': 'Julien Moreau', 'outsider': 'Sarah Benali'}
MONTHS = ('janvier', 'février', 'mars', 'avril', 'mai', 'juin', 'juillet', 'août', 'septembre', 'octobre',
          'novembre', 'décembre')


def load_dataset():
    """MISSIONS of demo_dataset.py, read as data. The k3s ConfigMap ships it gzipped, over 1 MiB otherwise."""
    here = Path(__file__).resolve().parent
    packed = here / 'demo_dataset.py.gz'
    source = gzip.decompress(packed.read_bytes()).decode() if packed.exists() else (here / 'demo_dataset.py').read_text()
    for node in ast.parse(source).body:
        if isinstance(node, ast.Assign) and getattr(node.targets[0], 'id', None) == 'MISSIONS':
            return ast.literal_eval(node.value)
    raise ValueError('MISSIONS absent du jeu de données')


MISSIONS = sorted(load_dataset(), key=lambda m: m['index'])
assert [m['index'] for m in MISSIONS] == list(range(40))


class ApiError(RuntimeError):
    pass


class Client:
    def __init__(self, passwords):
        self.passwords = passwords
        self.tokens = {}

    def login(self, name):
        form = urllib.parse.urlencode({'client_id': 'auditsphere-demo', 'grant_type': 'password',
                                       'username': name, 'password': self.passwords[name]}).encode()
        req = urllib.request.Request(TOKEN_URL,
                                     data=form, headers={'Content-Type': 'application/x-www-form-urlencoded'})
        try:
            with urllib.request.urlopen(req, timeout=15) as response:
                self.tokens[name] = json.load(response)['access_token']
        except urllib.error.HTTPError as exc:
            raise ApiError(f'Connexion {name}: HTTP {exc.code}') from None

    def subject(self, name):
        if name not in self.tokens:
            self.login(name)
        payload = self.tokens[name].split('.')[1]
        return json.loads(base64.urlsafe_b64decode(payload + '=' * (-len(payload) % 4)))['sub']

    def call(self, name, path, body=None, method=None, raw=None, content_type='application/json'):
        if name not in self.tokens:
            self.login(name)
        if raw is None and body is not None:
            raw = json.dumps(body, ensure_ascii=False).encode()
        for attempt in range(3):
            time.sleep(0.3)
            req = urllib.request.Request(BASE + path, data=raw, method=method,
                                         headers={'Authorization': 'Bearer ' + self.tokens[name],
                                                  'Content-Type': content_type})
            try:
                with urllib.request.urlopen(req, timeout=20) as response:
                    data = response.read()
                    return json.loads(data) if data else None
            except urllib.error.HTTPError as exc:
                if exc.code == 401 and attempt == 0:
                    self.login(name)
                    continue
                if exc.code == 429 and attempt < 2:
                    time.sleep(min(60, int(exc.headers.get('Retry-After', '60')) + 1))
                    continue
                raise ApiError(f'{method or "GET"} {path}: HTTP {exc.code}') from None
            except (OSError, TimeoutError) as exc:
                raise ApiError(f'{method or "GET"} {path}: connexion interrompue ({type(exc).__name__})') from None
        raise ApiError(f'{method or "GET"} {path}: tentatives épuisées')

    def upload(self, name, path, filename, media_type, content):
        boundary = uuid.uuid4().hex
        raw = (f'--{boundary}\r\nContent-Disposition: form-data; name="file"; filename="{filename}"\r\n'
               f'Content-Type: {media_type}\r\n\r\n').encode() + content + f'\r\n--{boundary}--\r\n'.encode()
        return self.call(name, path, raw=raw, method='POST', content_type='multipart/form-data; boundary=' + boundary)


def passwords_from_env():
    # This file is local and ignored by Git. Never print values or HTTP response bodies.
    values = {}
    for line in ACCOUNTS.read_text().splitlines():
        if '=' in line and not line.lstrip().startswith('#'):
            key, value = line.split('=', 1)
            values[key] = value.strip().strip('"').strip("'")
    return {name: values[name.upper() + '_PASSWORD'] for name in ('manager', 'auditor', 'outsider', 'validator')}


def save_manifest(state):
    MANIFEST.parent.mkdir(exist_ok=True)
    os.chmod(MANIFEST.parent, 0o700)
    temporary = MANIFEST.with_suffix('.tmp')
    with temporary.open('w') as stream:
        os.chmod(temporary, 0o600)
        json.dump(state, stream, ensure_ascii=False, indent=2)
        stream.write('\n')
    os.replace(temporary, MANIFEST)


def all_missions(api):
    result = []
    page = 0
    while True:
        batch = api.call('manager', f'/missions?page={page}&size=100')
        result.extend(batch['items'])
        if len(result) >= batch['total']:
            return result
        page += 1


def kind(index):
    if index < 8:
        return 'DRAFT'
    if index < 20:
        return ('REJECTED' if index in (9, 13, 17) else
                'WITHDRAWN' if index in (11, 18) else 'IN_PROGRESS')
    if index < 27:
        return 'PENDING_REVIEW'
    if index < 34:
        return 'APPROVED'
    return 'CLOSED'


def dates(anchor, index):
    # A mix of overdue, current and future plans, all relative to the first run.
    if index == 0:
        return None, None
    if index in (7, 19, 26):
        return (anchor - dt.timedelta(days=14)).isoformat(), anchor.isoformat()
    if index < 8:
        start, end = ((-35, -5) if index % 3 == 0 else (7 + index, 28 + index))
    elif index < 20:
        start, end = ((-70, -10 - index % 7) if index % 2 == 0 else (-12, 16 + index))
    elif index < 27:
        start, end = ((-50, -(index % 12) - 1) if index % 2 else (-20, 12))
    else:
        start, end = -90 - index, -15 - index % 20
    return ((anchor + dt.timedelta(days=start)).isoformat(),
            (anchor + dt.timedelta(days=end)).isoformat())


TOKEN = re.compile(r'\{(date|month|quarter|year):([+-]?\d+)\}')


def expand(value, anchor):
    """Replace the relative date tokens of the dataset, so the documents stay current after each nightly reset."""
    if isinstance(value, list):
        return [expand(v, anchor) for v in value]
    if isinstance(value, dict):
        return {k: expand(v, anchor) for k, v in value.items()}
    if not isinstance(value, str):
        return value

    def replace(match):
        unit, offset = match.group(1), int(match.group(2))
        if unit == 'date':
            return (anchor + dt.timedelta(days=offset)).strftime('%d/%m/%Y')
        if unit == 'year':
            return str(anchor.year + offset)
        if unit == 'month':
            month = anchor.year * 12 + anchor.month - 1 + offset
            return f'{MONTHS[month % 12]} {month // 12}'
        quarter = anchor.year * 4 + (anchor.month - 1) // 3 + offset
        return f'T{quarter % 4 + 1} {quarter // 4}'

    return TOKEN.sub(replace, value)


def team(case, index):
    """Account names of the mission team, lead first."""
    if case['team'] == 'both':
        return ['auditor', 'outsider'] if index % 2 == 0 else ['outsider', 'auditor']
    return [case['team']]


def recorded(index, number):
    # In-progress missions show work under way: two controls concluded, evidence already gathered on a third.
    target = kind(index)
    if target == 'DRAFT':
        return False, False
    if target == 'IN_PROGRESS':
        return number < 2, number < 3
    return True, True


def reconcile_program(api, mission, case, members, anchor):
    mid, index = mission['id'], case['index']
    program = api.call('manager', f'/missions/{mid}/program')
    for risk in case['risks']:
        matches = [r for r in program['risks'] if r['title'] == risk['title']]
        if len(matches) > 1:
            raise ApiError(f'{case["title"]}: risque ambigu')
        if not matches:
            program = api.call('manager', f'/missions/{mid}/risks', {
                'version': program['mission']['version'], 'title': risk['title'],
                'description': expand(risk['description'], anchor),
                'probability': risk['probability'], 'impact': risk['impact']}, 'PUT')
    risk_ids = {r['title']: r['id'] for r in program['risks']}
    for control in case['controls']:
        matches = [c for c in program['controls'] if c['objective'] == control['objective']]
        if len(matches) > 1:
            raise ApiError(f'{case["title"]}: contrôle ambigu')
        if not matches:
            program = api.call('manager', f'/missions/{mid}/controls', {
                'version': program['mission']['version'], 'objective': control['objective'],
                'procedure': expand(control['procedure'], anchor),
                'riskIds': [risk_ids[case['risks'][r]['title']] for r in control['risks']]}, 'PUT')
    if kind(index) == 'DRAFT':
        return api.call('manager', f'/missions/{mid}')
    mission = api.call('manager', f'/missions/{mid}')
    if mission['status'] == 'DRAFT':
        mission = api.call('manager', f'/missions/{mid}/status',
                           {'version': mission['version'], 'status': 'IN_PROGRESS'}, 'PUT')
    if mission['status'] != 'IN_PROGRESS' or mission.get('reviewDecision') == 'REJECTED' or mission.get('withdrawnAt'):
        # Results, evidence and findings are frozen once the mission left its first execution.
        return mission
    controls = {c['objective']: c for c in program['controls']}
    year = anchor.year
    for number, control in enumerate(case['controls']):
        result, evidence = recorded(index, number)
        author = members[number % len(members)]
        saved = controls[control['objective']]
        if evidence:
            path = f'/missions/{mid}/controls/{saved["id"]}/evidence'
            present = {e['originalName'] for e in api.call(author, path)}
            for spec in control.get('evidence', []):
                if spec['file'] in present:
                    continue
                context = {'company': COMPANY, 'mission': case['title'],
                           'reference': f'AUD-{year}-{index + 1:03d} / C{number + 1}',
                           'author': NAMES[author],
                           'date': (anchor - dt.timedelta(days=12 - number * 2)).strftime('%d/%m/%Y')}
                content, media_type = demo_documents.render(expand(spec, anchor), context)
                version = api.call('manager', f'/missions/{mid}')['version']
                api.upload(author, f'{path}?version={version}', spec['file'], media_type, content)
        if result and saved['result'] is None:
            version = api.call('manager', f'/missions/{mid}')['version']
            api.call(author, f'/missions/{mid}/results', {
                'version': version, 'controlId': saved['id'], 'outcome': control['outcome'],
                'comment': expand(control['comment'], anchor)}, 'PUT')
    reconcile_findings(api, mid, case, members, controls, anchor)
    return api.call('manager', f'/missions/{mid}')


def reconcile_findings(api, mid, case, members, controls, anchor):
    index = case['index']
    submitted = kind(index) != 'IN_PROGRESS'
    lead = members[0]
    existing = {f['title']: f for f in api.call('manager', f'/missions/{mid}/findings')}
    for finding in case.get('findings', []):
        linked = [case['controls'][n] for n in finding['controls']]
        tested = [n for n in finding['controls'] if recorded(index, n)[0]]
        if not tested:
            continue
        current = existing.get(finding['title'])
        if current is None:
            current = api.call(lead, f'/missions/{mid}/findings', {
                'title': finding['title'],
                **{field: expand(finding[field], anchor) for field in
                   ('condition', 'criterion', 'cause', 'consequence', 'recommendation')},
                'severity': finding['severity'],
                'controlIds': [controls[c['objective']]['id'] for c in linked]}, 'POST')
        decision = finding['decision']
        comment = expand(finding.get('decisionComment') or '', anchor)
        # A submitted mission cannot hold draft or submitted findings: they end validated or rejected.
        if submitted and decision in ('DRAFT', 'SUBMIT'):
            decision = 'VALIDATE'
        final = {'DRAFT': 'DRAFT', 'SUBMIT': 'SUBMITTED', 'VALIDATE': 'VALIDATED', 'REJECT': 'REJECTED',
                 'RETURN': 'VALIDATED' if submitted else 'DRAFT'}[decision]
        path = f'/missions/{mid}/findings/{current["id"]}'
        returned = decision != 'RETURN' or any(
            h['action'] == 'RETURNED' for h in api.call('manager', path + '/history'))
        for _ in range(6):
            status = current['status']
            if status == final and returned:
                break
            if status == 'DRAFT':
                body = {'action': 'SUBMIT'}
                actor = lead
            elif status == 'SUBMITTED' and not returned:
                body = {'action': 'RETURN', 'comment': comment}
                actor = 'manager'
                returned = True
            elif status == 'SUBMITTED':
                action = 'REJECT' if final == 'REJECTED' else 'VALIDATE'
                body = {'action': action}
                if action == 'REJECT':
                    body['comment'] = comment
                actor = 'manager'
            else:
                raise ApiError(f'{case["title"]}: constat dans un état inattendu ({status})')
            current = api.call(actor, path + '/transition', {'version': current['version'], **body}, 'PUT')
        else:
            raise ApiError(f'{case["title"]}: constat non réconcilié')


def review_text(case, key, fallback, anchor):
    return expand((case.get('review') or {}).get(key) or fallback, anchor)


def reconcile_status(api, mission, case, validator_subject, anchor):
    mid, index = mission['id'], case['index']
    target = kind(index)
    if target in ('DRAFT', 'IN_PROGRESS'):
        if mission['status'] != target:
            raise ApiError(f'{mission["title"]}: statut inattendu {mission["status"]}')
        return mission
    if target in ('REJECTED', 'WITHDRAWN') and mission['status'] == 'IN_PROGRESS':
        if target == 'REJECTED' and mission['reviewDecision'] == 'REJECTED':
            return reopen_first_finding(api, mission, case, anchor)
        if target == 'WITHDRAWN' and mission['withdrawnAt']:
            return mission
    if mission['status'] == 'IN_PROGRESS':
        if mission['validatorSubject'] != validator_subject:
            if mission['validatorSubject'] is not None:
                raise ApiError(f'{mission["title"]}: validateur différent')
            mission = api.call('manager', f'/missions/{mid}/validator',
                               {'version': mission['version'], 'validatorSubject': validator_subject}, 'PUT')
        mission = api.call('manager', f'/missions/{mid}/submission', {'version': mission['version']}, 'PUT')
    if target == 'PENDING_REVIEW':
        if mission['status'] != target:
            raise ApiError(f'{mission["title"]}: statut inattendu {mission["status"]}')
        return mission
    if mission['status'] == 'PENDING_REVIEW':
        if target == 'WITHDRAWN':
            mission = api.call('manager', f'/missions/{mid}/withdrawal', {
                'version': mission['version'],
                'reason': review_text(case, 'withdraw', 'Retrait pour revoir le périmètre avant une nouvelle soumission.', anchor)}, 'PUT')
        else:
            decision = 'REJECTED' if target == 'REJECTED' else 'APPROVED'
            mission = api.call('validator', f'/missions/{mid}/review', {
                'version': mission['version'], 'decision': decision,
                'comment': (review_text(case, 'reject', 'Corrections demandées avant approbation.', anchor)
                            if decision == 'REJECTED' else
                            review_text(case, 'approve', 'Travaux et constats approuvés.', anchor))}, 'PUT')
    if target == 'REJECTED':
        if mission['status'] != 'IN_PROGRESS':
            raise ApiError(f'{mission["title"]}: décision inattendue')
        return reopen_first_finding(api, mission, case, anchor)
    if target == 'WITHDRAWN':
        if mission['status'] != 'IN_PROGRESS':
            raise ApiError(f'{mission["title"]}: retrait inattendu')
    elif target == 'APPROVED':
        if mission['status'] != 'APPROVED':
            raise ApiError(f'{mission["title"]}: approbation inattendue')
    elif target == 'CLOSED':
        if mission['status'] == 'APPROVED':
            mission = api.call('manager', f'/missions/{mid}/status',
                               {'version': mission['version'], 'status': 'CLOSED'}, 'PUT')
        if mission['status'] != 'CLOSED':
            raise ApiError(f'{mission["title"]}: clôture inattendue')
    return mission


def reopen_first_finding(api, mission, case, anchor):
    # The manager reopens the finding the validator challenged, as the rejection comment asks.
    mid = mission['id']
    findings = api.call('manager', f'/missions/{mid}/findings')
    if any(f['status'] == 'DRAFT' for f in findings):
        return mission
    validated = [f for f in findings if f['status'] == 'VALIDATED']
    if validated:
        first = min(validated, key=lambda f: f['reference'])
        api.call('manager', f'/missions/{mid}/findings/{first["id"]}/transition', {
            'version': first['version'], 'action': 'REOPEN',
            'comment': review_text(case, 'reopen', 'Constat rouvert pour répondre au validateur.', anchor)}, 'PUT')
    return api.call('manager', f'/missions/{mid}')


def plan():
    counts = {status: sum(kind(i) == status for i in range(40)) for status in
              ('DRAFT', 'IN_PROGRESS', 'REJECTED', 'WITHDRAWN', 'PENDING_REVIEW', 'APPROVED', 'CLOSED')}
    risks = sum(len(m['risks']) for m in MISSIONS)
    controls = sum(len(m['controls']) for m in MISSIONS)
    evidence = sum(len(c.get('evidence', [])) for m in MISSIONS for n, c in enumerate(m['controls'])
                   if recorded(m['index'], n)[1])
    findings = sum(1 for m in MISSIONS for f in m.get('findings', [])
                   if any(recorded(m['index'], n)[0] for n in f['controls']))
    print(f'Plan : 40 missions, {risks} risques, {controls} contrôles, {evidence} justificatifs, {findings} constats.')
    print(f'Scénarios : {counts}.')


def render_all(folder, anchor):
    """Write every evidence file locally, for review without the API."""
    folder.mkdir(parents=True, exist_ok=True)
    total = 0
    for case in MISSIONS:
        for number, control in enumerate(case['controls']):
            for spec in control.get('evidence', []):
                context = {'company': COMPANY, 'mission': case['title'],
                           'reference': f'AUD-{anchor.year}-{case["index"] + 1:03d} / C{number + 1}',
                           'author': NAMES[team(case, case['index'])[0]], 'date': anchor.strftime('%d/%m/%Y')}
                content, _ = demo_documents.render(expand(spec, anchor), context)
                (folder / f'{case["index"]:02d}-C{number + 1}-{spec["file"]}').write_bytes(content)
                total += 1
    print(f'{total} justificatifs écrits dans {folder}.')


def main():
    parser = argparse.ArgumentParser(description='Préparer les 40 missions fictives du jeu de démonstration')
    parser.add_argument('--apply', action='store_true', help='Créer ou reprendre les missions via l’API')
    parser.add_argument('--render', type=Path, help='Écrire les justificatifs dans ce dossier, sans appel à l’API')
    args = parser.parse_args()
    if args.render:
        render_all(args.render, dt.date.today())
        return
    if not args.apply:
        plan()
        print('Aucune écriture. Exécuter avec --apply après sauvegarde et préflight.')
        return
    if not ACCOUNTS.exists():
        raise ApiError('Fichier des comptes absent')
    if MANIFEST.exists():
        state = json.loads(MANIFEST.read_text())
        if state.get('seedId') != IDENT or not isinstance(state.get('missions'), dict):
            raise ApiError('Manifeste privé incompatible')
        anchor = dt.date.fromisoformat(state['anchorDate'])
    else:
        anchor = dt.datetime.now(dt.timezone.utc).date()
        state = {'seedId': IDENT, 'anchorDate': anchor.isoformat(), 'missions': {}}
    save_manifest(state)
    api = Client(passwords_from_env())
    subjects = {name: api.subject(name) for name in ('auditor', 'outsider', 'validator')}
    existing = all_missions(api)
    by_title = {}
    for item in existing:
        by_title.setdefault(item['title'], []).append(item)
    missing = sum(case['title'] not in by_title for case in MISSIONS)
    if len(existing) + missing > 100:
        raise ApiError(f'Capacité prudente dépassée : {len(existing)} missions visibles + {missing} à créer > 100')
    started = time.monotonic()
    for case in MISSIONS:
        index, title = case['index'], case['title']
        matches = by_title.get(title, [])
        if len(matches) > 1:
            raise ApiError(f'Titre ambigu : {title}')
        if matches and IDENT not in matches[0]['description']:
            raise ApiError(f'Titre déjà utilisé hors de ce jeu : {title}')
        saved = state['missions'].get(str(index))
        if saved and matches and saved != matches[0]['id']:
            raise ApiError(f'Manifeste incohérent : {title}')
        if saved and not matches:
            raise ApiError(f'Mission du manifeste absente : {title}')
        if str(index) in state.get('completed', []):
            print(f'{index + 1}/40 : déjà créé, conservé sans modification', flush=True)
            continue
        members = team(case, index)
        if matches:
            mission = matches[0]
        else:
            start, end = dates(anchor, index)
            mission = api.call('manager', '/missions', {
                'title': title,
                'description': expand(case['description'], anchor) +
                               f'\n\nDonnées fictives de démonstration ({IDENT}).',
                'perimeter': expand(case['perimeter'], anchor),
                'assigneeSubjects': [subjects[m] for m in members],
                'plannedStartDate': start, 'plannedEndDate': end}, 'POST')
            by_title[title] = [mission]
        state['missions'][str(index)] = mission['id']
        save_manifest(state)
        mission = reconcile_program(api, mission, case, members, anchor)
        reconcile_status(api, mission, case, subjects['validator'], anchor)
        state.setdefault('completed', []).append(str(index))
        save_manifest(state)
        print(f'{index + 1}/40 : {title} [{kind(index)}] {time.monotonic() - started:.0f} s', flush=True)
    print('Terminé : 40 missions fictives réconciliées. Aucun compte ni mission existante supprimé.')


if __name__ == '__main__':
    try:
        main()
    except (ApiError, KeyError, ValueError, OSError) as exc:
        # Never include response bodies, passwords or JWTs in errors.
        raise SystemExit(f'Arrêt sûr : {exc}') from None
